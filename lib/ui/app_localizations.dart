class AppLocalizations {
  const AppLocalizations(this.locale);

  final Locale locale;

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations)!;

  static const delegate = _AppLocalizationsDelegate();

  String text(String source, [Map<String, Object?> values = const {}]) {
    var result = source;
    final index = _languageIndexes[locale.languageCode];
    if (index != null) {
      final translations = _translations[source];
      if (translations != null && index < translations.length) {
        result = translations[index];
      } else {
        result = _translations[source]?.first ?? source;
      }
    }
    for (final entry in values.entries) {
      result = result.replaceAll('{${entry.key}}', entry.value.toString());
    }
    return result;
  }

  String message(String source) {
    if (source.startsWith('设备报告协议错误：')) {
      final code = source.substring('设备报告协议错误：'.length);
      return '${text('Device protocol error')}: $code';
    }
    return text(source);
  }
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => supportedAppLocales.any(
    (value) => value.languageCode == locale.languageCode,
  );

  @override
  Future<AppLocalizations> load(Locale locale) =>
      SynchronousFuture(AppLocalizations(locale));

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

extension AppLocalizationsContext on BuildContext {
  AppLocalizations get l10n => AppLocalizations.of(this);
}

class AppLocaleController extends ChangeNotifier {
  static const _preferenceKey = 'app_locale';

  Locale _locale = supportedAppLocales.first;
  bool _disposed = false;

  Locale get locale => _locale;

  Future<void> load() async {
    try {
      final preferences = await SharedPreferences.getInstance();
      final code = preferences.getString(_preferenceKey);
      Locale? locale;
      for (final value in supportedAppLocales) {
        if (value.languageCode == code) {
          locale = value;
          break;
        }
      }
      if (!_disposed && locale != null && locale != _locale) {
        _locale = locale;
        notifyListeners();
      }
    } on Object {
      // 语言设置读取失败时继续使用中文，不阻止应用启动。
    }
  }

  Future<void> setLocale(Locale locale) async {
    if (!supportedAppLocales.any(
      (value) => value.languageCode == locale.languageCode,
    )) {
      return;
    }
    if (_locale != locale) {
      _locale = locale;
      notifyListeners();
    }
    try {
      final preferences = await SharedPreferences.getInstance();
      await preferences.setString(_preferenceKey, locale.languageCode);
    } on Object {
      // 保存失败不影响本次语言切换。
    }
  }

  @override
  void dispose() {
    _disposed = true;
    super.dispose();
  }
}
